export interface KnowledgeNote {
  id: string
  projectId: string | null
  title: string
  categoryPath: string
  filePath: string
  content: string
  /** False when a listing left the content out to stay within its size budget; fetch the note to get it. */
  contentLoaded?: boolean
  autoGenerated: boolean
  tags: string[]
  createdAt: string
  updatedAt: string
}

export interface KnowledgeCategory {
  name: string
  path: string
  children: KnowledgeCategory[]
  notes: KnowledgeNote[]
}
